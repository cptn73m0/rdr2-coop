#!/usr/bin/env python3
"""Generate src/gen_metaped_outfits.h from
third_party/rdr3-discoveries/clothes/metaped_outfits.lua.

RDR2 string hash is the RAGE/GTA variant of joaat (lowercase):
    h = 0
    for c in s.lower(): h += c; h += h << 10; h ^= h >> 6
    h += h << 3; h ^= h >> 11; h += h << 15

The generated header exposes:
    struct MetaOutfitModelEntry { uint32_t modelHash; uint32_t first; uint16_t count; };
    kMetaOutfitHashes[]  - flat array of candidate outfit hashes
    kMetaOutfitModels[]  - sorted by modelHash
    LookupMetaOutfits(uint32_t modelHash, const uint32_t** hashes, uint16_t* count)
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LUA = os.path.join(ROOT, 'third_party', 'rdr3-discoveries', 'clothes',
                   'metaped_outfits.lua')
OUT = os.path.join(ROOT, 'src', 'gen_metaped_outfits.h')


def joaat(text: str) -> int:
    h = 0
    for c in text.lower().encode('utf-8'):
        h = (h + c) & 0xFFFFFFFF
        h = (h + (h << 10)) & 0xFFFFFFFF
        h ^= h >> 6
    h = (h + (h << 3)) & 0xFFFFFFFF
    h ^= h >> 11
    h = (h + (h << 15)) & 0xFFFFFFFF
    return h


def parse_blocks(text: str):
    blocks = {}
    for m in re.finditer(r'\["([a-zA-Z0-9_]+)"\]\s*=\s*\{', text):
        name = m.group(1)
        start = m.end()
        depth = 1
        i = start
        while i < len(text) and depth > 0:
            c = text[i]
            if c == '{':
                depth += 1
            elif c == '}':
                depth -= 1
            i += 1
        body = text[start:i]
        hashes = []
        for hm in re.finditer(r'\{0x([0-9A-Fa-f]{8})\}', body):
            v = int(hm.group(1), 16)
            if v not in hashes:
                hashes.append(v)
        if hashes:
            blocks[name] = hashes
    return blocks


def main():
    text = open(LUA, encoding='utf-8', errors='ignore').read()
    blocks = parse_blocks(text)
    models = []
    flat = []
    for name, hashes in blocks.items():
        models.append((joaat(name), name, len(flat), len(hashes)))
        flat.extend(hashes)
    models.sort(key=lambda x: x[0])

    lines = []
    lines.append('// Generated by tools/gen_metaped_outfits.py - do not edit.')
    lines.append('// Source: third_party/rdr3-discoveries/clothes/metaped_outfits.lua')
    lines.append('#pragma once')
    lines.append('')
    lines.append('#include <cstdint>')
    lines.append('')
    lines.append('namespace metaped_outfits {')
    lines.append('')
    lines.append('struct ModelEntry {')
    lines.append('    uint32_t modelHash;')
    lines.append('    uint32_t first;')
    lines.append('    uint16_t count;')
    lines.append('};')
    lines.append('')
    lines.append('static const uint32_t kOutfitHashes[] = {')
    for i in range(0, len(flat), 8):
        chunk = ', '.join('0x%08Xu' % v for v in flat[i:i + 8])
        lines.append('    ' + chunk + ',')
    lines.append('};')
    lines.append('')
    lines.append('static const ModelEntry kModels[] = {')
    for h, name, first, count in models:
        lines.append('    {0x%08Xu, %du, %du}, // %s' % (h, first, count, name))
    lines.append('};')
    lines.append('')
    lines.append('constexpr uint32_t kModelCount = %du;' % len(models))
    lines.append('constexpr uint32_t kHashCount = %du;' % len(flat))
    lines.append('')
    lines.append('inline bool LookupMetaOutfits(uint32_t modelHash,')
    lines.append('                                const uint32_t** hashes,')
    lines.append('                                uint16_t* count)')
    lines.append('{')
    lines.append('    uint32_t lo = 0;')
    lines.append('    uint32_t hi = kModelCount;')
    lines.append('    while (lo < hi)')
    lines.append('    {')
    lines.append('        const uint32_t mid = (lo + hi) / 2;')
    lines.append('        if (kModels[mid].modelHash < modelHash)')
    lines.append('            lo = mid + 1;')
    lines.append('        else')
    lines.append('            hi = mid;')
    lines.append('    }')
    lines.append('    if (lo >= kModelCount || kModels[lo].modelHash != modelHash)')
    lines.append('        return false;')
    lines.append('    *hashes = &kOutfitHashes[kModels[lo].first];')
    lines.append('    *count = kModels[lo].count;')
    lines.append('    return true;')
    lines.append('}')
    lines.append('')
    lines.append('} // namespace metaped_outfits')
    lines.append('')

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('models=%d hashes=%d -> %s' % (len(models), len(flat), OUT))


if __name__ == '__main__':
    main()
